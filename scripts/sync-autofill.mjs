#!/usr/bin/env node
/**
 * Generates the per-platform copies of the shared autofill engine from
 * shared/autofill/engine.js. Run `npm run sync:autofill` after editing the engine;
 * `npm run sync:autofill -- --check` fails if any generated copy is stale (CI / tests).
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const source = fs.readFileSync(path.join(root, 'shared/autofill/engine.js'), 'utf8')
const start = source.indexOf('function loonieAutofill(')
if (start < 0) throw new Error('shared/autofill/engine.js must define function loonieAutofill(')
const fn = source.slice(start).trim()

const banner =
  '// AUTO-GENERATED by scripts/sync-autofill.mjs from shared/autofill/engine.js — do not edit.\n'

const tsModule =
  banner +
  '/* eslint-disable */\n' +
  '/** Source of the self-contained `loonieAutofill(profile)` function, for page injection. */\n' +
  `export const AUTOFILL_ENGINE_SOURCE: string = ${JSON.stringify(fn)}\n`

const extModule = banner + `export ${fn}\n`

const outputs = {
  'src/lib/autofill/engine.generated.ts': tsModule,
  'mobile/src/lib/autofill/engine.generated.ts': tsModule,
  'extension/lib/engine.generated.js': extModule,
}

const check = process.argv.includes('--check')
let stale = 0
for (const [rel, content] of Object.entries(outputs)) {
  const file = path.join(root, rel)
  const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null
  if (current === content) continue
  if (check) {
    console.error(`stale: ${rel} (run npm run sync:autofill)`)
    stale++
  } else {
    fs.writeFileSync(file, content)
    console.log(`wrote ${rel}`)
  }
}
if (stale) process.exit(1)
